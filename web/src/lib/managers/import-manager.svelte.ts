import { SvelteSet } from 'svelte/reactivity';
import type { TakeoutAlbum } from '$lib/utils/google-takeout-parser';
import type { ScanProgress, ScanResult } from '$lib/utils/google-takeout-scanner';

export enum ImportStep {
  Files = 0,
  Scan = 1,
  Review = 2,
  Import = 3,
}

export interface ImportOptions {
  importFavorites: boolean;
  importArchived: boolean;
  importDescriptions: boolean;
  skipDuplicates: boolean;
}

export interface ImportProgress {
  imported: number;
  skipped: number;
  errors: number;
  total: number;
  currentFile: string;
  currentAlbum: string;
  albumsCreated: number;
  errorLog: Array<{ file: string; error: string }>;
}

function defaultOptions(): ImportOptions {
  return {
    importFavorites: true,
    importArchived: true,
    importDescriptions: true,
    skipDuplicates: true,
  };
}

function defaultProgress(): ImportProgress {
  return {
    imported: 0,
    skipped: 0,
    errors: 0,
    total: 0,
    currentFile: '',
    currentAlbum: '',
    albumsCreated: 0,
    errorLog: [],
  };
}

export class ImportManager {
  currentStep = $state<ImportStep>(ImportStep.Files);
  selectedFiles = $state<File[]>([]);
  scanResult = $state<ScanResult | undefined>(undefined);
  scanProgress = $state<ScanProgress | undefined>(undefined);
  selectedAlbums = $state<Set<string>>(new SvelteSet());
  options = $state<ImportOptions>(defaultOptions());
  importProgress = $state<ImportProgress>(defaultProgress());
  isPaused = $state<boolean>(false);
  isComplete = $state<boolean>(false);

  totalSize = $derived(this.selectedFiles.reduce((sum, file) => sum + file.size, 0));

  nextStep() {
    if (this.currentStep < ImportStep.Import) {
      this.currentStep++;
    }
  }

  previousStep() {
    if (this.currentStep > ImportStep.Files) {
      this.currentStep--;
    }
  }

  reset() {
    this.currentStep = ImportStep.Files;
    this.selectedFiles = [];
    this.scanResult = undefined;
    this.scanProgress = undefined;
    this.selectedAlbums = new SvelteSet();
    this.options = defaultOptions();
    this.importProgress = defaultProgress();
    this.isPaused = false;
    this.isComplete = false;
  }

  addFiles(files: File[]) {
    this.selectedFiles = [...this.selectedFiles, ...files];
  }

  clearFiles() {
    this.selectedFiles = [];
  }

  setAlbums(albums: TakeoutAlbum[]) {
    this.selectedAlbums = new SvelteSet(albums.filter((a) => !a.isAutoGenerated).map((a) => a.name));
  }

  toggleAlbum(name: string) {
    const next = new SvelteSet(this.selectedAlbums);
    if (next.has(name)) {
      next.delete(name);
    } else {
      next.add(name);
    }
    this.selectedAlbums = next;
  }

  selectAllAlbums() {
    if (!this.scanResult) {
      return;
    }
    this.selectedAlbums = new SvelteSet(this.scanResult.albums.map((a) => a.name));
  }

  deselectAllAlbums() {
    this.selectedAlbums = new SvelteSet();
  }

  togglePause() {
    this.isPaused = !this.isPaused;
  }
}
